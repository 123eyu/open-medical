import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright-core';
import { fixture } from './helpers.mjs';

test('project drafts and attachments remain isolated in page memory with cancellable refresh protection', {timeout:60000}, async t => {
  const root = mkdtempSync(join(tmpdir(),'synthetic-project-drafts-'));
  t.after(()=>rmSync(root,{recursive:true,force:true}));
  const f = await fixture(t,{provider:{apiKey:'synthetic',model:'synthetic-draft-test',async complete(){return {message:{role:'assistant',content:'合成任务已接收'}};}}});
  const create = async title => (await f.json('/api/workspaces','POST',{root,title,directoryConsent:true})).data;
  const a = await create('虚构草稿项目甲'), b = await create('虚构草稿项目乙');
  const browser = await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
  t.after(()=>browser.close());
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  page.setDefaultTimeout(10000);
  const errors = []; page.on('pageerror',error=>errors.push(error.message));
  const dialogs = []; page.on('dialog',async dialog=>{dialogs.push(dialog.type());await dialog.dismiss();});
  const input = page.getByRole('textbox',{name:'项目任务',exact:true});
  const open = async project => {
    await page.getByRole('button',{name:'查看全部项目文件',exact:true}).click();
    await page.getByRole('main',{name:'项目目录'}).locator('.directory-open').filter({hasText:project.title}).click();
    await page.locator('.conversation-head h1').filter({hasText:project.title}).waitFor();
  };
  const blockedReload = async () => {
    const before = dialogs.length;
    await assert.rejects(page.reload({timeout:3000}),/ERR_ABORTED|Navigation.*cancel|interrupted|Timeout/);
    assert.equal(dialogs.length,before+1); assert.equal(dialogs.at(-1),'beforeunload');
  };
  await page.goto(`${f.origin}/?view=workspaces&workspace=${a.id}`);
  await input.fill('虚构甲未发送内容 7319');
  const chooser = page.waitForEvent('filechooser');
  await page.getByRole('button',{name:'材料',exact:true}).click();
  await (await chooser).setFiles({name:'虚构附件.txt',mimeType:'text/plain',buffer:Buffer.from('虚构未发送附件正文 8247')});
  await page.getByRole('button',{name:'移除 虚构附件.txt',exact:true}).waitFor();
  await blockedReload(); assert.equal(await input.inputValue(),'虚构甲未发送内容 7319');
  await open(b); assert.equal(await input.inputValue(),'');
  assert.equal(await page.getByRole('button',{name:'移除 虚构附件.txt',exact:true}).count(),0);
  await input.fill('虚构乙未发送内容 9351');
  await open(a); assert.equal(await input.inputValue(),'虚构甲未发送内容 7319');
  await page.getByRole('button',{name:'移除 虚构附件.txt',exact:true}).waitFor();
  const storage = await page.evaluate(()=>JSON.stringify({local:{...localStorage},session:{...sessionStorage}}));
  assert.doesNotMatch(storage,/7319|8247|9351/,'draft bodies never enter browser storage');
  assert.equal((await f.json(`/api/workspaces/${a.id}`)).data.messages.length,0);
  assert.equal((await f.json(`/api/workspaces/${b.id}`)).data.messages.length,0);
  await page.getByRole('button',{name:'查看全部项目文件',exact:true}).click();
  await blockedReload();
  await page.getByRole('main',{name:'项目目录'}).locator('.directory-open').filter({hasText:a.title}).click();
  await input.waitFor(); assert.equal(await input.inputValue(),'虚构甲未发送内容 7319');
  await input.fill('');
  await page.getByRole('button',{name:'移除 虚构附件.txt',exact:true}).click();
  await open(b); assert.equal(await input.inputValue(),'虚构乙未发送内容 9351');
  await input.fill('');
  const before = dialogs.length;
  await page.reload(); await input.waitFor();
  assert.equal(dialogs.length,before,'empty drafts do not obstruct refresh');
  await input.fill('仅接收这个合成任务');
  await page.route(`**/api/workspaces/${b.id}/runs`,route=>route.abort('failed'),{times:1});
  await page.locator('.composer button[type=submit]').click();
  await page.getByText('Failed to fetch',{exact:true}).waitFor();
  assert.equal(await input.inputValue(),'仅接收这个合成任务');
  await blockedReload();
  await page.locator('.composer button[type=submit]').click();
  await page.getByText('合成任务已接收',{exact:true}).first().waitFor();
  assert.equal(await input.inputValue(),'');
  await page.reload(); await input.waitFor(); assert.equal(dialogs.length,before+1,'accepted submission clears its draft protection');
  const saved = (await f.json(`/api/workspaces/${b.id}`)).data;
  assert.equal(saved.runs.length,1); assert.equal(saved.messages.filter(m=>m.role==='user').length,1);
  assert.deepEqual(errors,[]);
});
