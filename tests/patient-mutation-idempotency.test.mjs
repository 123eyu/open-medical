import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fixture } from './helpers.mjs';

test('clinical mutation retry survives restart, preserves later edits, and rejects changed submissions', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'patient-mutation-'));
  const database = join(dir, 'synthetic.sqlite');
  const cleanups = [];
  const context = { after: fn => cleanups.push(fn) };
  let f = await fixture(context, { database, followupOptions: { autoStart: false } });
  t.after(async () => { for (const cleanup of cleanups.reverse()) await cleanup(); rmSync(dir, { recursive: true, force: true }); });
  const p = (await f.json('/api/patients', 'POST', { name: '虚构保存重试甲' })).data;
  const q = (await f.json('/api/patients', 'POST', { name: '虚构保存重试乙' })).data;
  const url = `/api/patients/${p.id}`;
  const visit = { date: '2026-01-01', reason: '虚构复诊' };
  const payload = { expectedRevision: 0, visits: [visit], requestId: 'same-clinical-save' };
  const [first, repeated] = await Promise.all([f.json(url, 'PATCH', payload), f.json(url, 'PATCH', payload)]);
  assert.equal(first.status, 200); assert.equal(repeated.status, 200);
  assert.equal(first.data.revision, 1); assert.equal(repeated.data.revision, 1);
  assert.equal((await f.json(url)).data.visits.length, 1);
  assert.equal((await f.json(url, 'PATCH', { ...payload, visits: [{ ...visit, reason: '不同内容' }] })).status, 409);
  assert.equal((await f.json(url, 'PATCH', { expectedRevision: 0, note: '普通陈旧写入' })).status, 409);
  assert.equal((await f.json(url, 'PATCH', { expectedRevision: 1, note: '另一医生的更新' })).status, 200);
  await cleanups.pop()();
  f = await fixture(context, { database, followupOptions: { autoStart: false } });
  const afterRestart = await f.json(url, 'PATCH', payload);
  assert.equal(afterRestart.status, 200); assert.equal(afterRestart.data.revision, 2);
  assert.equal(afterRestart.data.note, '另一医生的更新'); assert.equal(afterRestart.data.visits.length, 1);
  assert.equal((await f.json(`/api/patients/${q.id}`, 'PATCH', payload)).status, 200);
  assert.equal((await f.json(url, 'PATCH', { expectedRevision: 2, visits: [visit, visit], requestId: 'intentional-second-save' })).data.visits.length, 2);
});
