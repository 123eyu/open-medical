import test from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
import { chromium } from "playwright-core";
import { fixture } from "./helpers.mjs";

// Uses only a memory database and synthetic identities; no chat/model execution.
test("patient intake keeps identities, import rows and uploaded materials bound through navigation", { timeout: 120000 }, async (t) => {
  const f = await fixture(t, { followupOptions: { autoStart: false } });
  const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: process.env.DOCTOR_UI_HEADED !== "1" });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(10000);
  const evidence = process.env.DOCTOR_UI_EVIDENCE;
  if (evidence) mkdirSync(evidence, { recursive: true });
  const snap = async (name) => {
    if (!evidence) return;
    await page.screenshot({ path: `${evidence}/${name}.png`, fullPage: true });
    writeFileSync(`${evidence}/${name}.txt`, await page.locator("body").innerText());
  };
  const click = (name) => page.getByRole("button", { name, exact: true }).click();
  const card = (number) => page.locator(".patient-card").filter({ hasText: number });
  const textVisible = (text) => page.getByText(text, { exact: true }).first().waitFor();
  try {
    await page.goto(f.origin + "/?view=patients");
    await click("手动建档");
    await page.getByLabel("姓名 *", { exact: true }).fill("虚构安全甲");
    await page.getByLabel("患者编号（可选）").fill("SAFE-A");
    await page.getByLabel("或按年龄填（岁）").fill("40");
    assert.equal(await page.getByLabel("出生年份", { exact: true }).inputValue(), String(new Date().getFullYear() - 40));
    await page.getByLabel("出生年份", { exact: true }).fill("1990");
    assert.equal(await page.getByLabel("或按年龄填（岁）").inputValue(), "");
    await snap("optimize-age");
    await click("创建患者档案");
    await click("← 返回列表");
    await card("SAFE-A").waitFor();
    const a = (await f.json("/api/patients")).data.patients.find((p) => p.patientNumber === "SAFE-A");
    assert.equal(a.birthYear, 1990);
    const b = (await f.json("/api/patients", "POST", {name:a.name, patientNumber:"SAFE-B", confirmDistinctPatient:true})).data;
    const archived = (await f.json("/api/patients", "POST", {name:"虚构归档核验", patientNumber:"RESTORED-1"})).data;
    await f.json(`/api/patients/${archived.id}`, "PATCH", {archived:true, expectedRevision:0});
    await page.reload();
    await click("手动建档");
    await page.getByLabel("姓名 *", { exact: true }).fill(archived.name);
    await page.getByRole("button", {name:/RESTORED-1.*已归档.*打开并恢复档案/}).waitFor();
    assert.equal(await page.getByRole("button", {name:"创建患者档案",exact:true}).isDisabled(),true);
    await snap("optimize-archived-manual");
    await click("关闭");
    await click("导入患者表格");
    await page.getByLabel("患者表格文本").fill(`姓名,患者编号\n${archived.name},RESTORED-2`);
    await click("预览并检查");
    await page.getByRole("button", {name:"打开并恢复 · RESTORED-1",exact:true}).waitFor();
    assert.equal(await page.getByRole("checkbox").isChecked(),false);
    await snap("optimize-archived-import");
    await click("打开并恢复 · RESTORED-1");
    await page.locator(".patient-more summary").click();
    await click("恢复患者");
    await textVisible("患者已恢复到在管列表。");
    assert.equal((await f.json(`/api/patients/${archived.id}`)).data.archived,false);
    await card("SAFE-A").click();
    assert.equal(await page.getByText("患者已恢复到在管列表。",{exact:true}).count(),0);
    await click("← 返回列表");
    await click("导入患者表格");
    await page.getByLabel("患者表格文本").fill("姓名,患者编号,出生年份\n\n虚构重复甲,DUP,1980\n\n虚构重复乙,DUP,2099");
    await click("预览并检查");
    await textVisible("2 条需修正");
    for (const row of [3,5]) assert.equal(await page.getByLabel(`选择第 ${row} 行`,{exact:true}).isDisabled(),true);
    await snap("optimize-import-conflicts");
    await click("返回修改表格");
    await page.getByLabel("患者表格文本").fill("姓名,患者编号,出生年份\n\n虚构批次新患者,SAFE-NEW,1980");
    await click("预览并检查");
    await click("新建 1 位患者");
    await card("SAFE-NEW").waitFor();
    await page.reload();
    await card("SAFE-NEW").waitFor();
    await page.getByRole("button",{name:"导入患者表格",exact:true}).waitFor();
    const search = page.getByPlaceholder("姓名、编号、电话、标签或诊断");
    await search.fill(" safe-a ");
    await card("SAFE-A").waitFor();
    assert.equal(await page.locator(".patient-card").count(),1);
    await snap("optimize-normalized-search");
    await search.fill("");
    await click("导入检验结果");
    await page.getByLabel("检验表格文本").fill("姓名,患者编号,项目,数值,日期\n虚构姓名冲突,SAFE-B,虚构指标,5,2026-10-01");
    await click("预览并匹配");
    await page.getByText(/姓名与编号不一致/).waitFor();
    assert.equal(await page.getByRole("checkbox").isDisabled(),true);
    assert.equal(await page.getByRole("button",{name:"生成 0 行检验提案",exact:true}).isDisabled(),true);
    await snap("optimize-lab-conflict");
    await click("关闭");
    await card("SAFE-A").click();
    await page.waitForFunction(() => document.title.includes("SAFE-A"));
    const otherTab = await browser.newPage();
    await otherTab.goto(f.origin + `/?view=patients&patient=${b.id}&tab=overview`);
    await otherTab.waitForFunction(() => document.title.includes("SAFE-B"));
    assert.notEqual(await page.title(), await otherTab.title());
    await otherTab.close();
    await click("资料库");
    await page.getByRole("button",{name:"添加第一份资料",exact:true}).waitFor();
    let release, entered;
    const gate = new Promise((resolve) => { release = resolve; });
    const seen = new Promise((resolve) => { entered = resolve; });
    await page.route(f.origin + `/api/sessions/${a.sessionId}`, async (route) => { entered(); await gate; await route.continue(); });
    await click("添加第一份资料");
    await seen;
    try {
      assert.equal(await page.getByRole("button",{name:"附件",exact:true}).isDisabled(),true);
      await snap("optimize-upload-loading");
    } finally { release(); }
    await page.getByRole("button",{name:"患者档案",exact:true}).waitFor();
    await page.unrouteAll({behavior:"wait"});
    const chooser = page.waitForEvent("filechooser");
    await click("附件");
    await (await chooser).setFiles([
      {name:"截图20261017.txt",mimeType:"text/plain",buffer:Buffer.from("报告日期：2026-10-01\n虚构正文甲")},
      {name:"报告2026-10-01至2026-10-17.txt",mimeType:"text/plain",buffer:Buffer.from("文书日期：2026-10-17\n虚构正文乙")},
      {name:"病理报告.txt",mimeType:"text/plain",buffer:Buffer.from("病理诊断：虚构样本，仅用于软件验证")},
    ]);
    await page.getByText(/材料已保存。图片保留原图/).waitFor();
    const saved = (await f.json(`/api/sessions/${a.sessionId}`)).data;
    assert.equal(saved.files.length,3); assert.equal(saved.patientId,a.id);
    assert.equal((await f.json(`/api/sessions/${b.sessionId}`)).data.files.length,0);
    assert.equal((await f.json("/api/sessions")).data.sessions.length,4);
    await click("患者档案"); await click("资料库");
    const library = page.getByRole("navigation",{name:"资料文件列表"});
    await library.getByRole("button").filter({hasText:"截图20261017.txt"}).click();
    await page.getByText(/资料日期待核对：文件名 2026-10-17；正文文书日期 2026-10-01/).waitFor();
    await snap("optimize-date-conflict");
    await page.getByText("类型与资料日期",{exact:true}).click();
    assert.equal(await page.getByRole("button",{name:/采纳推测 2026/}).count(),0);
    await page.getByLabel("资料日期",{exact:true}).fill("2026-10-01");
    await textVisible("资料信息已保存");
    await page.reload();
    await library.getByRole("button").filter({hasText:"截图20261017.txt"}).click();
    await page.getByText("类型与资料日期",{exact:true}).click();
    assert.equal(await page.getByLabel("资料日期",{exact:true}).inputValue(),"2026-10-01");
    await library.getByRole("button").filter({hasText:"报告2026-10-01至2026-10-17.txt"}).click();
    await page.getByText(/资料日期待核对：文件名 2026-10-01；文件名 2026-10-17；正文文书日期 2026-10-17/).waitFor();
    await library.getByRole("button").filter({hasText:"病理报告.txt"}).click();
    if (!await page.getByLabel("资料类型",{exact:true}).isVisible()) await page.getByText("类型与资料日期",{exact:true}).click();
    assert.equal(await page.getByLabel("资料类型",{exact:true}).inputValue(),"病理报告");
    await page.getByLabel("资料类型",{exact:true}).selectOption("其他");
    await textVisible("资料信息已保存");
    await page.reload();
    await library.getByRole("button").filter({hasText:"病理报告.txt"}).click();
    await page.getByText("类型与资料日期",{exact:true}).click();
    assert.equal(await page.getByLabel("资料类型",{exact:true}).inputValue(),"其他");
    await snap("optimize-material-saved");
    await click("← 返回列表"); await card("SAFE-B").click(); await click("资料库");
    await textVisible("尚未关联资料文件。");
    await page.goto(f.origin+"/?view=tasks");
    const task = page.locator(".task-directory-row").filter({hasText:"SAFE-A"});
    await task.waitFor();
    await page.locator(".task-directory-row").filter({hasText:"SAFE-B"}).waitFor();
    await snap("optimize-task-identities");
    await task.click(); await click("患者档案");
    await page.waitForFunction(() => document.title.includes("SAFE-A"));
    console.log("Chrome: 建档、恢复、表格修正提交、检验冲突、上传加载锁、材料分类日期保存刷新、患者隔离及任务归属全部通过");
  } catch (error) { await snap("optimize-ui-error"); throw error; }
});
